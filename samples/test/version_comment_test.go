package test

import (
	"bufio"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// versionCommentHeaderLines is how many lines from the top of a file to search for the version comment.
const versionCommentHeaderLines = 5

// wagGeneratedFiles returns the Go, JS, and TypeScript files in dir that wag writes itself. Files
// generated afterwards by other tools (e.g. mockgen) and dependencies are skipped.
func wagGeneratedFiles(t *testing.T, dir string) []string {
	files := []string{}
	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			if info.Name() == "node_modules" {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasPrefix(info.Name(), "mock_") {
			return nil
		}
		switch filepath.Ext(path) {
		case ".go", ".js", ".ts":
			files = append(files, path)
		}
		return nil
	})
	require.NoError(t, err)
	require.NotEmpty(t, files, "no generated files found in %s", dir)
	return files
}

// hasVersionComment reports whether the top of the file contains a wag version comment.
func hasVersionComment(t *testing.T, path string) bool {
	f, err := os.Open(path)
	require.NoError(t, err)
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for i := 0; i < versionCommentHeaderLines && scanner.Scan(); i++ {
		if strings.Contains(scanner.Text(), "This file was generated by wag") {
			return true
		}
	}
	require.NoError(t, scanner.Err())
	return false
}

func TestOmitVersionComment(t *testing.T) {
	dirs, err := filepath.Glob("../gen-*")
	require.NoError(t, err)
	for _, dir := range dirs {
		for _, path := range wagGeneratedFiles(t, dir) {
			assert.False(t, hasVersionComment(t, path),
				"%s was generated with -omit-version-comment and shouldn't contain a version comment", path)
		}
	}
}
